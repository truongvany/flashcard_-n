// 90-day activity calendar generation
export function generateActivityHistory(): DayActivity[] {
  const result: DayActivity[] = [];
  const today = new Date();

  for (let i = 89; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(today.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];

    // Simulate realistic activity with streaks and high consistency
    const isWeekend = d.getDay() === 0 || d.getDay() === 6;
    const randomSeed = (i * 13 + d.getDate() * 7) % 100;

    let count = 0;
    if (i < 14) {
      // Current active streak (last 14 days)
      count = 20 + (randomSeed % 25);
    } else if (randomSeed > 18) {
      count = 12 + (randomSeed % 28);
      if (isWeekend) count = Math.max(8, Math.floor(count * 0.7));
    }

    const accuracy = count > 0 ? 82 + (randomSeed % 16) : 0;
    result.push({
      date: dateStr,
      count,
      accuracy,
    });
  }

  return result;
}
